CREATE TABLE IF NOT EXISTS CLV_SCORED_STAGING (
    ACCOUNT_ID VARCHAR(50),
    ARRAY_ID VARCHAR(50),
    BASELINE_CHURN_PROBABILITY FLOAT,
    PREVALENCE_CHURN_PROBABILITY FLOAT,
    RF_CHURN_PROBABILITY FLOAT,
    XGB_CHURN_PROBABILITY FLOAT,
    CHURN_PROBABILITY_12M FLOAT,
    RISK_BUCKET VARCHAR(20),
    MODEL_VERSION VARCHAR(50),
    SCORED_AT_UTC VARCHAR(60)
);

CREATE TABLE IF NOT EXISTS CLV_SCORED_OUTPUT (
    ACCOUNT_ID VARCHAR(50),
    ARRAY_ID VARCHAR(50),
    BASELINE_CHURN_PROBABILITY FLOAT,
    PREVALENCE_CHURN_PROBABILITY FLOAT,
    RF_CHURN_PROBABILITY FLOAT,
    XGB_CHURN_PROBABILITY FLOAT,
    CHURN_PROBABILITY_12M FLOAT,
    RISK_BUCKET VARCHAR(20),
    MODEL_VERSION VARCHAR(50),
    SCORED_AT_UTC TIMESTAMP_TZ,
    LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);