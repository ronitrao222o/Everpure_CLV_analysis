USE DATABASE EVERPURE_CLV;
USE SCHEMA ANALYTICS;

MERGE INTO CLV_SCORED_OUTPUT AS target
USING (
    SELECT
        ACCOUNT_ID,
        ARRAY_ID,
        BASELINE_CHURN_PROBABILITY,
        PREVALENCE_CHURN_PROBABILITY,
        RF_CHURN_PROBABILITY,
        XGB_CHURN_PROBABILITY,
        CHURN_PROBABILITY_12M,
        RISK_BUCKET,
        MODEL_VERSION,
        TRY_TO_TIMESTAMP_TZ(SCORED_AT_UTC) AS SCORED_AT_UTC
    FROM CLV_SCORED_STAGING
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY ARRAY_ID, MODEL_VERSION
        ORDER BY TRY_TO_TIMESTAMP_TZ(SCORED_AT_UTC) DESC
    ) = 1
) AS source

ON target.ARRAY_ID = source.ARRAY_ID
AND target.MODEL_VERSION = source.MODEL_VERSION

WHEN MATCHED THEN UPDATE SET
    target.ACCOUNT_ID = source.ACCOUNT_ID,
    target.BASELINE_CHURN_PROBABILITY =
        source.BASELINE_CHURN_PROBABILITY,
    target.PREVALENCE_CHURN_PROBABILITY =
        source.PREVALENCE_CHURN_PROBABILITY,
    target.RF_CHURN_PROBABILITY =
        source.RF_CHURN_PROBABILITY,
    target.XGB_CHURN_PROBABILITY =
        source.XGB_CHURN_PROBABILITY,
    target.CHURN_PROBABILITY_12M =
        source.CHURN_PROBABILITY_12M,
    target.RISK_BUCKET = source.RISK_BUCKET,
    target.SCORED_AT_UTC = source.SCORED_AT_UTC

WHEN NOT MATCHED THEN INSERT (
    ACCOUNT_ID,
    ARRAY_ID,
    BASELINE_CHURN_PROBABILITY,
    PREVALENCE_CHURN_PROBABILITY,
    RF_CHURN_PROBABILITY,
    XGB_CHURN_PROBABILITY,
    CHURN_PROBABILITY_12M,
    RISK_BUCKET,
    MODEL_VERSION,
    SCORED_AT_UTC
)
VALUES (
    source.ACCOUNT_ID,
    source.ARRAY_ID,
    source.BASELINE_CHURN_PROBABILITY,
    source.PREVALENCE_CHURN_PROBABILITY,
    source.RF_CHURN_PROBABILITY,
    source.XGB_CHURN_PROBABILITY,
    source.CHURN_PROBABILITY_12M,
    source.RISK_BUCKET,
    source.MODEL_VERSION,
    source.SCORED_AT_UTC
);