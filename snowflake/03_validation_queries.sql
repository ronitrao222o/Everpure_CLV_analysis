USE DATABASE EVERPURE_CLV;
USE SCHEMA ANALYTICS;

-- 1. Verify row counts
SELECT
    (SELECT COUNT(*) FROM CLV_SCORED_STAGING)
        AS STAGING_ROWS,
    (SELECT COUNT(*) FROM CLV_SCORED_OUTPUT)
        AS OUTPUT_ROWS;

-- 2. Check duplicate array/model combinations
SELECT ARRAY_ID, MODEL_VERSION, COUNT(*) AS N
FROM CLV_SCORED_OUTPUT
GROUP BY ARRAY_ID, MODEL_VERSION
HAVING COUNT(*) > 1;

-- 3. Check invalid probabilities and missing fields
SELECT
    COUNT_IF(ARRAY_ID IS NULL) AS MISSING_ARRAY_IDS,
    COUNT_IF(CHURN_PROBABILITY_12M IS NULL)
        AS MISSING_SCORES,
    COUNT_IF(
        CHURN_PROBABILITY_12M < 0
        OR CHURN_PROBABILITY_12M > 1
    ) AS INVALID_SCORES,
    COUNT_IF(SCORED_AT_UTC IS NULL)
        AS INVALID_TIMESTAMPS
FROM CLV_SCORED_OUTPUT;

-- 4. Risk distribution
SELECT
    RISK_BUCKET,
    COUNT(*) AS ARRAY_COUNT,
    ROUND(AVG(CHURN_PROBABILITY_12M), 4)
        AS AVG_CHURN_PROBABILITY
FROM CLV_SCORED_OUTPUT
GROUP BY RISK_BUCKET
ORDER BY RISK_BUCKET;

-- 5. Inspect final records
SELECT *
FROM CLV_SCORED_OUTPUT
LIMIT 10;